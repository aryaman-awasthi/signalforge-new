"""Generate docs/03-stories.md as a view over specs/requirements.yaml.

Stories are generated, never handwritten: the requirement catalogue is the
single source of truth; this renders it per persona (artifact 03).

Usage: python scripts/gen_stories.py [--out PATH]
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]

PERSONA_BY_AREA = {
    "engineering-guide": ("platform engineer", "the platform stays buildable, traceable and app-agnostic"),
    "platform-identity": ("org owner", "my organisation is secure, isolated and manageable"),
    "event-backbone": ("platform engineer", "nothing is lost, everything is ordered and replayable"),
    "integrations": ("app team member", "my application onboards through public contracts without custom code"),
    "detection-lifecycle": ("on-call engineer", "real trouble is caught early and false alarms stay quiet"),
    "war-room": ("incident commander", "the right people are in the room with shared, current state"),
    "incident-brain": ("incident commander", "I can trust and interrogate every AI conclusion"),
    "governance-execution": ("incident commander", "remediation is fast but can never outrun policy or approval"),
    "drills-audit": ("auditor", "every incident is replayable, reviewable and turned into practice"),
}

AREA_TITLES = {
    "engineering-guide": "Foundations and engineering guide",
    "platform-identity": "Platform and identity",
    "event-backbone": "Event backbone",
    "integrations": "Integrations and onboarding",
    "detection-lifecycle": "Detection and lifecycle",
    "war-room": "War room and people",
    "incident-brain": "Incident brain",
    "governance-execution": "Governance and execution",
    "drills-audit": "Drills, audit, learning",
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "03-stories.md")
    args = parser.parse_args()

    spec = yaml.safe_load((ROOT / "specs" / "requirements.yaml").read_text(encoding="utf-8"))
    by_area: dict[str, list[dict]] = defaultdict(list)
    for req in spec["requirements"]:
        by_area[req["area"]].append(req)

    lines = [
        "# 03 - Stories (generated view)",
        "",
        "GENERATED by scripts/gen_stories.py from specs/requirements.yaml - do not edit.",
        f"Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        "",
    ]
    for area, title in AREA_TITLES.items():
        reqs = by_area.get(area, [])
        if not reqs:
            continue
        persona, benefit = PERSONA_BY_AREA[area]
        lines.append(f"## {title}")
        lines.append("")
        for req in reqs:
            first = req["title"][0].lower() + req["title"][1:]
            lines.append(
                f"- **{req['id']}** ({req['sprint']}, {req['priority']}, {req['status']}): "
                f"As a {persona}, I want {first}, so that {benefit}."
            )
            lines.append(f"  - Acceptance: {' '.join(str(req['acceptance']).split())}")
        lines.append("")

    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"gen_stories: wrote {args.out} ({sum(len(v) for v in by_area.values())} stories)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
