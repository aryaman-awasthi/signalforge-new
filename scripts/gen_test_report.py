"""Generates docs/21-test-report.md (artifact 21) from var/rtm/test-results.json,
the same recording the RTM uses. Run via `make report` after `make test`."""

from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "var" / "rtm" / "test-results.json"
OUTPUT = ROOT / "docs" / "21-test-report.md"


def main() -> int:
    if not RESULTS.is_file():
        print("gen_test_report: no var/rtm/test-results.json - run `make test` first")
        return 2
    payload = json.loads(RESULTS.read_text(encoding="utf-8"))
    tests: dict[str, dict] = payload["tests"]

    outcomes = Counter(t["outcome"] or "not-run" for t in tests.values())
    by_module: dict[str, Counter] = defaultdict(Counter)
    by_req: dict[str, Counter] = defaultdict(Counter)
    for nodeid, entry in tests.items():
        module = nodeid.split("::", 1)[0].replace("\\", "/")
        by_module[module][entry["outcome"] or "not-run"] += 1
        for req in entry["reqs"]:
            by_req[req][entry["outcome"] or "not-run"] += 1

    lines = [
        "# 21 - Test execution report",
        "",
        "GENERATED by scripts/gen_test_report.py (make report) - do not edit.",
        f"Source run recorded: {payload['generated_at']}  |  "
        f"report generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        "",
        "## Summary",
        "",
        f"- total tests: {len(tests)}",
    ]
    for outcome in sorted(outcomes):
        lines.append(f"- {outcome}: {outcomes[outcome]}")
    lines += ["", "## By module", "", "| Module | passed | failed | other |", "|---|---|---|---|"]
    for module in sorted(by_module):
        c = by_module[module]
        other = sum(v for k, v in c.items() if k not in ("passed", "failed"))
        lines.append(f"| {module} | {c['passed']} | {c['failed']} | {other} |")
    lines += ["", "## By requirement", "", "| REQ | passed | failed | other |", "|---|---|---|---|"]
    for req in sorted(by_req):
        c = by_req[req]
        other = sum(v for k, v in c.items() if k not in ("passed", "failed"))
        lines.append(f"| {req} | {c['passed']} | {c['failed']} | {other} |")
    untagged = sorted(n for n, t in tests.items() if not t["reqs"])
    lines += ["", "## Untagged tests", ""]
    lines += [f"- {n}" for n in untagged] or ["- none"]
    lines.append("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"gen_test_report: wrote {OUTPUT.relative_to(ROOT)} ({len(tests)} tests)")
    return 1 if outcomes.get("failed") else 0


if __name__ == "__main__":
    sys.exit(main())
