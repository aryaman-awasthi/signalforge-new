"""Generate docs/20-RTM.md from specs/requirements.yaml + recorded test results.

The RTM is generated, never handwritten (CLAUDE.md rule 5). It renders the full
requirement chain even with zero executed tests: requirements missing tests show
as untested rather than being dropped.

Usage: python scripts/gen_rtm.py [--out PATH] [--results PATH]
Exit codes: 0 generated; 2 integrity problem (test references an unknown REQ id).
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def load_requirements(path: Path) -> list[dict]:
    spec = yaml.safe_load(path.read_text(encoding="utf-8"))
    return spec["requirements"]


def load_results(path: Path) -> dict:
    if not path.is_file():
        return {"generated_at": None, "tests": {}}
    return json.loads(path.read_text(encoding="utf-8"))


def build_rtm(requirements: list[dict], results: dict) -> tuple[str, list[str]]:
    tests = results.get("tests", {})
    by_req: dict[str, list[tuple[str, str | None]]] = defaultdict(list)
    untagged: list[str] = []
    for nodeid, info in tests.items():
        reqs = info.get("reqs", [])
        if not reqs:
            untagged.append(nodeid)
        for req_id in reqs:
            by_req[req_id].append((nodeid, info.get("outcome")))

    known_ids = {r["id"] for r in requirements}
    unknown_refs = sorted(set(by_req) - known_ids)

    executed = {n for n, i in tests.items() if i.get("outcome") is not None}
    passed = {n for n, i in tests.items() if i.get("outcome") == "passed"}
    covered = [r for r in requirements if by_req.get(r["id"])]

    lines: list[str] = []
    lines.append("# 20 - Requirements Traceability Matrix")
    lines.append("")
    lines.append("GENERATED by `make rtm` - do not edit by hand.")
    lines.append("")
    lines.append(f"- Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}")
    lines.append(f"- Test results from: {results.get('generated_at') or 'no recorded run'}")
    lines.append(f"- Requirements: {len(requirements)}"
                 f" | with linked tests: {len(covered)}"
                 f" | without: {len(requirements) - len(covered)}")
    lines.append(f"- Tests recorded: {len(tests)} | executed: {len(executed)} | passed: {len(passed)}")
    lines.append("")
    lines.append("| REQ | Title | Area | Sprint | Spec status | Tests | Verification |")
    lines.append("|---|---|---|---|---|---|---|")

    for req in requirements:
        linked = by_req.get(req["id"], [])
        if not linked:
            tests_cell = "-"
            verdict = "no tests linked"
        else:
            tests_cell = "<br>".join(f"`{n}`" for n, _ in linked)
            outcomes = [o for _, o in linked]
            # A skipped test is neither evidence nor a failure. Opt-in suites -
            # the live-gateway checks, which must never be on the critical path
            # - would otherwise report every requirement they touch as FAILING.
            ran = [o for o in outcomes if o is not None]
            failed = sum(1 for o in ran if o not in ("passed", "skipped"))
            skipped = sum(1 for o in ran if o == "skipped")
            if not ran:
                verdict = "not executed"
            elif failed:
                verdict = f"FAILING ({failed} not passing)"
            else:
                verdict = f"passed ({len(ran) - skipped}/{len(outcomes)} executed)"
                if skipped:
                    verdict += f", {skipped} skipped (opt-in)"
        lines.append(
            f"| {req['id']} | {req['title']} | {req['area']} | {req['sprint']}"
            f" | {req['status']} | {tests_cell} | {verdict} |"
        )

    lines.append("")
    if untagged:
        lines.append("## Tests without REQ markers (violates CLAUDE.md rule 5)")
        lines.extend(f"- `{n}`" for n in sorted(untagged))
        lines.append("")
    if unknown_refs:
        lines.append("## Tests referencing unknown REQ ids (fix specs or the marker)")
        for req_id in unknown_refs:
            for nodeid, _ in by_req[req_id]:
                lines.append(f"- {req_id}: `{nodeid}`")
        lines.append("")

    return "\n".join(lines) + "\n", unknown_refs


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "20-RTM.md")
    parser.add_argument("--results", type=Path, default=ROOT / "var" / "rtm" / "test-results.json")
    parser.add_argument("--specs", type=Path, default=ROOT / "specs" / "requirements.yaml")
    args = parser.parse_args()

    requirements = load_requirements(args.specs)
    results = load_results(args.results)
    rtm, unknown_refs = build_rtm(requirements, results)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(rtm, encoding="utf-8")
    print(f"gen_rtm: wrote {args.out} ({len(requirements)} requirements)")
    if unknown_refs:
        print(f"gen_rtm: ERROR - tests reference unknown REQ ids: {', '.join(unknown_refs)}")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
