"""Generates artifacts 16 and 17 from a run, never from a claim.

    make nfr        # after: pytest signalforge/tests/nfr

Artifact 16 (non-functional tests) is written from var/nfr/failure-catalogue.json
and the recorded test outcomes; artifact 17 (performance) is written from
var/nfr/performance.json. Both refuse to generate when their input is missing,
because a performance report with no measurements behind it is the exact thing
this repository must not ship.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NFR_DIR = ROOT / "var" / "nfr"
RESULTS = ROOT / "var" / "rtm" / "test-results.json"
NFR_DOC = ROOT / "docs" / "16-non-functional-tests.md"
PERF_DOC = ROOT / "docs" / "17-performance-tests.md"

STAMP = "GENERATED by scripts/gen_nfr_report.py (make nfr) - do not edit."


def _read(name: str) -> dict | None:
    path = NFR_DIR / f"{name}.json"
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _nfr_outcomes() -> list[tuple[str, str]]:
    if not RESULTS.is_file():
        return []
    payload = json.loads(RESULTS.read_text(encoding="utf-8"))
    rows = []
    for nodeid, entry in sorted(payload["tests"].items()):
        normalised = nodeid.replace("\\", "/")
        if "/tests/nfr/" not in normalised:
            continue
        rows.append((normalised, entry["outcome"] or "not-run"))
    return rows


def write_non_functional() -> int:
    catalogue = _read("failure-catalogue")
    if catalogue is None:
        print("gen_nfr_report: no var/nfr/failure-catalogue.json - run the nfr suite")
        return 2
    degraded = _read("degraded-mode") or {}
    outcomes = _nfr_outcomes()

    lines = [
        "# 16 - Non-functional tests",
        "",
        STAMP,
        f"Generated {datetime.now(timezone.utc).isoformat(timespec='seconds')}.",
        "",
        "## What this artifact is",
        "",
        "CLAUDE.md ground rule 6 requires every designed failure to land somewhere",
        "safe, observable and recoverable, with a test. This document is generated",
        "from the run of `signalforge/tests/nfr`, so it can only list failure paths",
        "the suite actually exercised.",
        "",
        "## Failure catalogue",
        "",
        "| Failure | Designed landing place |",
        "|---|---|",
    ]
    for failure, landing in sorted(catalogue["paths"].items()):
        lines.append(f"| {failure} | {landing} |")

    lines += [
        "",
        "## Degraded mode",
        "",
        "The release-critical path was exercised with no `GENAILAB_API_KEY` present.",
        "Every AI-backed read answered and reported itself degraded rather than",
        "hiding it:",
        "",
        "| Read | degraded |",
        "|---|---|",
    ]
    for name, flag in sorted((degraded.get("degraded_flags") or {}).items()):
        lines.append(f"| {name} | {flag} |")
    if not degraded.get("degraded_flags"):
        lines.append("| _no degraded-mode measurement recorded_ | - |")

    lines += ["", "## Executed tests", "", "| Test | Outcome |", "|---|---|"]
    for nodeid, outcome in outcomes:
        lines.append(f"| `{nodeid}` | {outcome} |")
    if not outcomes:
        lines.append("| _no recorded run_ | - |")

    lines += [
        "",
        "## Limitations",
        "",
        "- These are functional proofs of failure behaviour, not endurance tests.",
        "  Nothing here runs for hours or under sustained concurrency.",
        "- The websocket-fallback and crash-recovery paths are proven in their own",
        "  suites (`signalforge/tests/test_web_warroom.py`,",
        "  `signalforge/tests/events/test_crash_recovery.py`) and referenced here",
        "  rather than duplicated.",
        "",
    ]
    NFR_DOC.write_text("\n".join(lines), encoding="utf-8")
    print(f"gen_nfr_report: wrote {NFR_DOC.relative_to(ROOT)}")
    return 0


def write_performance() -> int:
    measured = _read("performance")
    if measured is None:
        print("gen_nfr_report: no var/nfr/performance.json - run the nfr suite")
        return 2
    environment = measured["environment"]
    operations = measured["operations"]

    lines = [
        "# 17 - Performance tests and results",
        "",
        STAMP,
        f"Generated {datetime.now(timezone.utc).isoformat(timespec='seconds')}.",
        "",
        "## What was measured, and what was not",
        "",
        "Representative cockpit reads on an incident that has a graph, an execution",
        "ledger with an approval, a validation cycle and a communication - because",
        "benchmarking an empty incident measures an empty incident.",
        "",
        "**This is not a load test and no production-scale claim is made.** The build",
        "is one machine, SQLite WAL and a single process (CLAUDE.md environment), and",
        "a synthetic thousand-user figure from that would be a number about nothing.",
        "",
        "## Environment",
        "",
        "| Property | Value |",
        "|---|---|",
    ]
    for key, value in environment.items():
        lines.append(f"| {key} | {value} |")

    lines += [
        "",
        "## Results",
        "",
        "| Operation | Samples | Failures | Median (ms) | p95 (ms) | Min (ms) | Max (ms) |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, row in sorted(operations.items(), key=lambda kv: kv[1]["median_ms"]):
        lines.append(
            f"| {name} | {row['samples']} | {row['failures']} | "
            f"{row['median_ms']} | {row['p95_ms']} | {row['min_ms']} | {row['max_ms']} |"
        )

    slowest = max(operations.items(), key=lambda kv: kv[1]["p95_ms"])
    total_failures = sum(row["failures"] for row in operations.values())
    lines += [
        "",
        "## Reading these numbers",
        "",
        f"- {len(operations)} operations, "
        f"{environment.get('samples_per_operation')} samples each, "
        f"{total_failures} failure(s) in total.",
        f"- The slowest read at p95 is **{slowest[0]}** at "
        f"{slowest[1]['p95_ms']}ms.",
        "- Latencies are in-process over an ASGI transport: they exclude a socket",
        "  and a browser, and they include the whole application, the ORM and the",
        "  SQLite path. A number from a browser will be larger by the network.",
        "- The suite enforces a ceiling rather than a target, so a change that makes",
        "  a cockpit read an order of magnitude slower fails a test instead of",
        "  shipping quietly.",
        "",
        "## Limitations",
        "",
        "- Single-process, single-machine, no concurrency dimension.",
        "- SQLite rather than Postgres. The schema is Postgres-ready but these",
        "  numbers are not a Postgres prediction.",
        "- Detection latency, ingest burst throughput and websocket fan-out are",
        "  exercised functionally in their own suites and are not timed here.",
        "",
    ]
    PERF_DOC.write_text("\n".join(lines), encoding="utf-8")
    print(f"gen_nfr_report: wrote {PERF_DOC.relative_to(ROOT)}")
    return 0


def main() -> int:
    return max(write_non_functional(), write_performance())


if __name__ == "__main__":
    raise SystemExit(main())
